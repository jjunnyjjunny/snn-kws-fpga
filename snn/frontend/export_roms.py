"""
export_roms.py — write all front-end ROMs as $readmemh .mem files into snn/rom/.

Files (hex, one word per line, address = line number):
  hann_w480.mem / hann_w400.mem : 16-bit unsigned Q1.15 Hann window
  twiddle_re.mem / twiddle_im.mem: 16-bit signed Q1.15 (two's complement, 4 hex digits), depth 256
  mel40_table.mem / mel32_table.mem : per band: {start_bin[8:0], length[6:0], weight_offset[9:0]} packed 26-bit
  mel40_weights.mem / mel32_weights.mem : flat 8-bit unsigned weights (address = weight_offset + j)
  log2_lut.mem : 5-bit unsigned (values 0..16), depth 32
  decim_coef.mem : 16-bit signed Q1.15 FIR taps (if snn/runs/decim_coef_q15.npy exists)
plus snn/rom/README.md describing every file.
usage: python snn/frontend/export_roms.py
"""
import os, sys, json
import numpy as np
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, ROOT)
from snn.frontend import fe_config as C
from snn.frontend.frontend_ref import make_hann_q15, make_twiddle_q15, make_mel_sparse, make_log_lut
ROM = os.path.join(ROOT, 'snn', 'rom')

def to_hex(v, bits):
    v = int(v)
    if v < 0:
        v += 1 << bits
    assert 0 <= v < (1 << bits), (v, bits)
    return f"{v:0{(bits + 3) // 4}x}"

def write_mem(name, values, bits, comment):
    path = os.path.join(ROM, name)
    with open(path, 'w') as f:
        f.write(f"// {comment}\n// width={bits} depth={len(values)}\n")
        for v in values:
            f.write(to_hex(v, bits) + "\n")
    return path, len(values)

def main():
    os.makedirs(ROM, exist_ok=True)
    info = []
    for win in (480, 400):
        p, d = write_mem(f"hann_w{win}.mem", make_hann_q15(win), 16, f"periodic Hann, Q1.15 unsigned, win={win}")
        info.append((os.path.basename(p), 16, d, "addr n = sample index within frame; w[n] = 0.5-0.5cos(2*pi*n/WIN) * 32768, max 32767"))
    tr, ti = make_twiddle_q15()
    p, d = write_mem("twiddle_re.mem", tr, 16, "cos(2*pi*k/512), Q1.15 signed two's complement")
    info.append(("twiddle_re.mem", 16, d, "addr k = 0..255 ; W_512^k real = cos(2*pi*k/512) * 32768 (32767 max)"))
    p, d = write_mem("twiddle_im.mem", ti, 16, "-sin(2*pi*k/512), Q1.15 signed two's complement")
    info.append(("twiddle_im.mem", 16, d, "addr k = 0..255 ; W_512^k imag = -sin(2*pi*k/512) * 32768"))
    for nm in (40, 32):
        table, dense = make_mel_sparse(nm)
        flat, packed = [], []
        off = 0
        for (s, L, w) in table:
            packed.append((s << 17) | (L << 10) | off)
            flat.extend(int(v) for v in w)
            off += L
        assert off < 1024 and max(L for _, L, _ in table) < 128
        write_mem(f"mel{nm}_table.mem", packed, 26, "per-band {start_bin[25:17], length[16:10], weight_offset[9:0]}")
        write_mem(f"mel{nm}_weights.mem", flat, 8, "flat 8-bit unsigned triangular weights")
        info.append((f"mel{nm}_table.mem", 26, nm, "addr m = mel band; bits[25:17]=start_bin(0..256) bits[16:10]=length bits[9:0]=offset into weights ROM"))
        info.append((f"mel{nm}_weights.mem", 8, len(flat), "addr = table.offset + j, j=0..length-1 ; weight for bin start_bin+j (0..255 = 0..1.0)"))
        json.dump([dict(band=m, start=int(s), length=int(L), weights=[int(v) for v in w]) for m, (s, L, w) in enumerate(table)],
                  open(os.path.join(ROM, f"mel{nm}_table.json"), 'w'))
    lut = make_log_lut()
    write_mem("log2_lut.mem", lut, 5, "16*log2(1+(i+0.5)/32) rounded, i = 5 mantissa bits below leading one")
    info.append(("log2_lut.mem", 5, len(lut), "addr i = 5 bits right below the leading one; log2q = (lead_pos<<4) + LUT[i]"))
    dec = os.path.join(ROOT, 'snn', 'runs', 'decim_coef_q15.npy')
    if os.path.exists(dec):
        hq = np.load(dec)
        write_mem("decim_coef.mem", hq, 16, "48k->16k FIR, Q1.15 signed; polyphase phase p = h[3j+p]")
        info.append(("decim_coef.mem", 16, len(hq), "addr k = tap index; y[n] = (sum_k h[k] x[3n-k] + 2^14) >> 15 ; polyphase E_p[j]=h[3j+p]"))
    with open(os.path.join(ROM, 'README.md'), 'w') as f:
        f.write("# snn/rom — $readmemh ROM images for the KWS front-end / SNN\n\n")
        f.write("All files: one hex word per line, line index = address (after 2 comment lines starting with `//`).\n")
        f.write("Signed values are two's complement in the stated width. Generated by `snn/frontend/export_roms.py`\n")
        f.write("(front-end) and `snn/golden/export_snn_mem.py` (SNN weights).\n\n")
        f.write("## Front-end ROMs\n\n| file | width (bits) | depth | address / content rule |\n|---|---|---|---|\n")
        for n, b, d, r in info:
            f.write(f"| `{n}` | {b} | {d} | {r} |\n")
        f.write(f"""
## Fixed-point conventions (fe_config.py)
- PCM in: {C.PCM_BITS}-bit signed. Input scaling: `x_db = sat{C.FFT_DATA_BITS}((pcm + 2^{C.IN_SHIFT-1}) >> {C.IN_SHIFT})`.
- Framing: hop {C.HOP}, win {C.WIN}, T = {C.N_FRAMES} frames per 16000 samples, frame t = x[160t : 160t+WIN], zero-pad to 512.
- Window: `xw = sat{C.FFT_DATA_BITS}((x_db * hann + 2^14) >> 15)`.
- FFT: radix-2 DIT, bit-reversed input, 9 stages, twiddle index for stage s (m=2^s): k * (512/m).
  butterfly: `p = b*W` (complex, products {C.FFT_DATA_BITS}x16), `a' = sat((a<<15 + p + 2^15) >> 16)`, `b' = sat((a<<15 - p + 2^15) >> 16)`.
  Overall gain 1/512.
- Power: `P[k] = re^2 + im^2`, k = 0..256, unsigned {C.POW_BITS} bits, no truncation.
- Mel: `acc[m] = sum_j w[m,j] * P[start_m + j]`, unsigned {C.MEL_ACC_BITS}-bit accumulator.
- log2: `lead = position of leading one (0 for acc==0)`, `mant = 5 bits right below lead` (zero-extended if lead<5),
  `log2q = (lead << 4) + LUT[mant]` (10 bits), log2q(0) = 0.
- Feature: `f = clip(log2q - {C.LOG_OFFSET}, 0, 255)` (8-bit unsigned).
""")
    print("wrote", len(info), "ROM files +", os.path.join(ROM, 'README.md'))

if __name__ == '__main__':
    main()
